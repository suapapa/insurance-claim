# 질병 코드 매칭 패턴: 알파벳 대문자 + 숫자 2~4자리 (점 포함 가능, 예: H368, H400, S33.5, J20)
# 뒤에 괄호, 대괄호 또는 한글이 바로 이어지는 경우는 이미 설명이 있는 것으로 간주하여 치환 대상에서 제외
_CODE_RE = re.compile(r"\b([A-Z]\d{2}(?:\.?\d{1,2})?)\b(?!\s*[\(\[가-힣])")


def resolve_disease_code(code: str) -> str | None:
    """질병 코드(예: H368, H40.0)를 한국어 질병명으로 조회."""
    if not code:
        return None
    raw = code.strip().upper()
    norm = raw.replace(".", "")

    # 1. 완전 일치 (예: H368, H400, J209)
    if norm in KCD_CODES:
        return KCD_CODES[norm]

    # 2. 3자리 범주 검색 (예: H368 -> H36)
    if len(norm) > 3 and norm[:3] in KCD_CODES:
        return KCD_CODES[norm[:3]]

    # 3. 3자리 fallback 사전 검색
    if norm[:3] in CATEGORY_FALLBACK:
        return CATEGORY_FALLBACK[norm[:3]]

    return None


def format_diagnosis(text: str | None) -> str | None:
    """진단명 문자열에서 질병 코드만 있는 경우 한국어 질병명을 괄호로 병기.

    예:
      'H368, H400' -> 'H368(기타 망막장애), H400(녹내장의증(녹내장 의심))'
      'H368' -> 'H368(기타 망막장애)'
      '급성 기관지염' -> '급성 기관지염' (한글이 이미 있으면 보존)
      '요추 염좌 (S33.5)' -> '요추 염좌 (S33.5)' (이미 병기된 경우 보존)
    """
    if not text:
        return text
    s = text.strip()

    # 이미 한국어 질병명이 충분히 포함되어 있고 코드가 괄호 안에 들어가 있는 경우(예: '요추 염좌 (S33.5)')는 그대로 보존
    if re.search(r"[가-힣]{2,}.*?\([A-Z]\d{2}", s):
        return s

    def _replace(m: re.Match) -> str:
        code = m.group(1)
        desc = resolve_disease_code(code)
        if desc:
            return f"{code}({desc})"
        return code

    return _CODE_RE.sub(_replace, s)
